// createEmptyPAIC.ts
/*
  Este archivo sirve para que el sistema pueda crear
  el estado inicial de cualquier perfil PAIC.
 */

import type { PAICDocument } from "@/types/paic";

export function createEmptyPAIC(): PAICDocument {
  const now = new Date().toISOString();

  return {
    version : "0.2",
    createdAt : now,
    updatedAt : now,

    identity : {
      name : "",
      occupation : "",
      education : "",
      languages : [],
      location : "",
      summary : "",
    },

    // Vacías a propósito: solo se guarda lo que la persona elige.
    // Si se guardaran valores por defecto, al exportar parecerían preferencias
    // declaradas por ella (p. ej. "Prefers responses in English." a alguien que
    // solo habla español). Los valores por defecto se aplican al USAR el
    // contexto, no al guardarlo.
    preferences : {},

    skills : [],
    projects : [],
    goals : [],
    memories : [],

    metadata : {
      sourceProviders : [],
      exportedFrom : "paic-app",
      notes : "Empty PAIC document generated by PAIC v0.2",
    }
  };
}